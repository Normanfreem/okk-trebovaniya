HF = PatternFill('solid', fgColor='1F3864')
thin = Side(style='thin', color='BFBFBF')
B = Border(left=thin, right=thin, top=thin, bottom=thin)


def style_sheet(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    for c in ws[1]:
        c.font = Font(bold=True, color='FFFFFF'); c.fill = HF
        c.alignment = Alignment(wrap_text=True, vertical='center')
    ws.freeze_panes = 'A2'
    ws.auto_filter.ref = ws.dimensions
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical='top'); c.border = B


def build(path, date, rows, docs):
    wb = openpyxl.Workbook()
    wi = wb.active; wi.title = 'Инфо'
    wi.append(['Параметр', 'Значение'])
    wi.append(['Актуально на', date])
    wi.append(['Составил', 'ОКК'])
    wi.append(['Комментарий', 'Учебный образец, данные вымышлены'])
    style_sheet(wi, [18, 50])
    wi['B2'].font = Font(bold=True, color='C00000')

    wr = wb.create_sheet('Требования')
    wr.append(REQ_HEAD)
    for r in rows: wr.append(r)
    style_sheet(wr, [10, 14, 20, 16, 12, 24, 60, 18, 6, 11, 12, 13, 22])
    grey = PatternFill('solid', fgColor='EDEDED'); yel = PatternFill('solid', fgColor='FFF2CC')
    for row in wr.iter_rows(min_row=2):
        if row[9].value == 'Заменено':
            for c in row: c.fill = grey; c.font = Font(color='808080')
        elif row[11].value:
            for c in row: c.fill = yel
    n = 500
    for col, opts in [('E', 'Материал,Устройство,Приёмка'), ('J', 'Действует,Заменено')]:
        dv = DataValidation(type='list', formula1=f'"{opts}"', allow_blank=True)
        wr.add_data_validation(dv); dv.add(f'{col}2:{col}{n}')

    wd = wb.create_sheet('Документы')
    wd.append(DOC_HEAD)
    for d in docs: wd.append(d)
    style_sheet(wd, [18, 10, 50, 12, 26, 70])
    dv = DataValidation(type='list', formula1='"Проект,РД,Письмо,СП,ГОСТ,Памятка,Прочее"', allow_blank=True)
    wd.add_data_validation(dv); dv.add('B2:B500')

    wh = wb.create_sheet('Как заполнять')
    for line in [
        'Лист «Требования»: одна строка = одно требование к одному материалу/операции.',
        'Столбец «Требование»: пишите «Показатель - значение», пункты через точку с запятой. Приложение само разобьёт на строки.',
        'Столбец «Документ»: код из листа «Документы». «Стр.» — страница PDF, которая откроется при нажатии.',
        'Если письмо меняет требование: старой строке ставим Статус «Заменено» и «Заменено на» = ID новой строки; новую строку добавляем с датой изменения.',
        'Строки не удаляем — так сохраняется история.',
        'Лист «Документы»: «Файл PDF» — точное имя файла в папке «Документы».',
        'Перед отправкой обновите дату на листе «Инфо».',
        'Названия листов и заголовки столбцов не менять.',
    ]:
        wh.append([line])
    wh.column_dimensions['A'].width = 130
    wb.save(path)


